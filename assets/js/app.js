const root = document.documentElement;
const langSwitch = document.getElementById('langSwitch');
const menuBtn = document.getElementById('menuBtn');
const header = document.querySelector('.site-header');
let lang = localStorage.getItem('qutoof-lang') || 'ar';

function applyLanguage(next) {
  lang = next;
  localStorage.setItem('qutoof-lang', lang);
  root.lang = lang;
  root.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.title = lang === 'ar' ? 'قطوف للصناعات الغذائية | Qutoof Food Industries' : 'Qutoof Food Industries | Dates Production & Packaging';
  langSwitch.textContent = lang === 'ar' ? 'EN' : 'عربي';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang][key] !== undefined) el.innerHTML = translations[lang][key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (translations[lang][key] !== undefined) el.placeholder = translations[lang][key];
  });
}

langSwitch?.addEventListener('click', () => applyLanguage(lang === 'ar' ? 'en' : 'ar'));
applyLanguage(lang);

menuBtn?.addEventListener('click', () => {
  const open = header.classList.toggle('open');
  menuBtn.setAttribute('aria-expanded', String(open));
});

document.querySelectorAll('.nav-links a').forEach((a) => a.addEventListener('click', () => {
  header.classList.remove('open');
  menuBtn?.setAttribute('aria-expanded', 'false');
}));

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) entry.target.classList.add('is-visible');
  });
}, { threshold: 0.12 });

document.querySelectorAll('.reveal').forEach((el) => observer.observe(el));
window.addEventListener('scroll', () => header.classList.toggle('scrolled', window.scrollY > 8), { passive: true });
document.getElementById('year').textContent = new Date().getFullYear();
